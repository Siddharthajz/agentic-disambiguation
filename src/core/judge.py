class CachedJudge:
    """Wrapper around judge with result caching to avoid redundant API calls."""
    
    def __init__(self, judge: BaseJudge):
        """Initialize cached judge."""
        self.judge = judge
        self.cache = {}
    
    def _make_cache_key(self, judgment_type: str, *args) -> str:
        """Create cache key from judgment type and arguments."""
        import hashlib
        key_str = f"{judgment_type}:" + "|".join(str(arg) for arg in args)
        return hashlib.md5(key_str.encode()).hexdigest()
    
    async def judge_answer_similarity(
        self,
        question: str,
        generated_answer: str,
        ground_truth_answers: List[str]
    ) -> Dict[str, Any]:
        """Judge with caching."""
        cache_key = self._make_cache_key("similarity", question, generated_answer, tuple(ground_truth_answers))
        
        if cache_key in self.cache:
            logger.debug(f"Cache hit for similarity judgment")
            return self.cache[cache_key]
        
        result = await self.judge.judge_answer_similarity(question, generated_answer, ground_truth_answers)
        self.cache[cache_key] = result
        return result
    
    async def judge_disambiguation(
        self,
        question: str,
        generated_answer: str,
        ground_truth_interpretations: List[Dict[str, Any]],
        dataset: str = "ambignq"
    ) -> Dict[str, Any]:
        """Judge with caching."""
        cache_key = self._make_cache_key("disambiguation", question, generated_answer, tuple(str(i) for i in ground_truth_interpretations))
        
        if cache_key in self.cache:
            logger.debug(f"Cache hit for disambiguation judgment")
            return self.cache[cache_key]
        
        result = await self.judge.judge_disambiguation(question, generated_answer, ground_truth_interpretations, dataset)
        self.cache[cache_key] = result
        return result
    
    async def judge_long_form_answer(
        self,
        question: str,
        generated_answer: str,
        reference_answer: str
    ) -> Dict[str, Any]:
        """Judge with caching."""
        cache_key = self._make_cache_key("long_form", question, generated_answer, reference_answer)
        
        if cache_key in self.cache:
            logger.debug(f"Cache hit for long-form judgment")
            return self.cache[cache_key]
        
        result = await self.judge.judge_long_form_answer(question, generated_answer, reference_answer)
        self.cache[cache_key] = result
        return result
    
    def get_stats(self) -> Dict[str, int]:
        """Get cache statistics."""
        return {
            "cache_size": len(self.cache),
            "cached_judgments": len(self.cache)
        }
